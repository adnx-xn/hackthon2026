/**
 * Interpolates geographical coordinates based on the scalar values and threshold.
 */
function interpolateGeographic(threshold, val1, val2, coord1, coord2) {
  if (Math.abs(threshold - val1) < 0.00001) return coord1;
  if (Math.abs(threshold - val2) < 0.00001) return coord2;
  if (Math.abs(val1 - val2) < 0.00001) return coord1;

  const t = (threshold - val1) / (val2 - val1);
  return {
    lon: coord1.lon + t * (coord2.lon - coord1.lon),
    lat: coord1.lat + t * (coord2.lat - coord1.lat),
    depth: coord1.depth + t * (coord2.depth - coord1.depth)
  };
}

/**
 * Converts a geographic coordinate {lon, lat, depth} to spherical {x, y, z}
 * using the project's geoToSpherical function.
 */
function toSpherical(geoCoord, verticalExaggeration) {
  return geoToSpherical(geoCoord.lon, geoCoord.lat, geoCoord.depth, verticalExaggeration);
}

/**
 * Standard Marching Cubes Algorithm
 */
export function marchingCubes({
  data,
  nx,
  ny,
  nz,
  lon,
  lat,
  depth,
  threshold,
  verticalExaggeration
}) {
  const positions = [];
  
  // Allocate arrays for corners
  const vals = new Float32Array(8);
  const coords = new Array(8);
  const edgeVerts = new Array(12);

  // Indexing formula: index(z, y, x) = z * ny * nx + y * nx + x
  const ny_nx = ny * nx;

  // Pre-calculate coordinate arrays to avoid object creation in inner loop
  // But we need the physical values, so we just use the provided lon, lat, depth arrays.

  for (let z = 0; z < nz - 1; z++) {
    for (let y = 0; y < ny - 1; y++) {
      for (let x = 0; x < nx - 1; x++) {
        
        // Compute 1D indices for the 8 corners
        const idx0 = z * ny_nx + y * nx + x;
        const idx1 = z * ny_nx + y * nx + (x + 1);
        const idx2 = z * ny_nx + (y + 1) * nx + (x + 1);
        const idx3 = z * ny_nx + (y + 1) * nx + x;

        const idx4 = (z + 1) * ny_nx + y * nx + x;
        const idx5 = (z + 1) * ny_nx + y * nx + (x + 1);
        const idx6 = (z + 1) * ny_nx + (y + 1) * nx + (x + 1);
        const idx7 = (z + 1) * ny_nx + (y + 1) * nx + x;

        vals[0] = data[idx0];
        vals[1] = data[idx1];
        vals[2] = data[idx2];
        vals[3] = data[idx3];
        vals[4] = data[idx4];
        vals[5] = data[idx5];
        vals[6] = data[idx6];
        vals[7] = data[idx7];

        // NaN / Missing Data Handling
        // If ANY corner is NaN, SKIP this cube completely.
        if (
          Number.isNaN(vals[0]) || Number.isNaN(vals[1]) ||
          Number.isNaN(vals[2]) || Number.isNaN(vals[3]) ||
          Number.isNaN(vals[4]) || Number.isNaN(vals[5]) ||
          Number.isNaN(vals[6]) || Number.isNaN(vals[7])
        ) {
          continue;
        }

        let cubeIndex = 0;
        if (vals[0] < threshold) cubeIndex |= 1;
        if (vals[1] < threshold) cubeIndex |= 2;
        if (vals[2] < threshold) cubeIndex |= 4;
        if (vals[3] < threshold) cubeIndex |= 8;
        if (vals[4] < threshold) cubeIndex |= 16;
        if (vals[5] < threshold) cubeIndex |= 32;
        if (vals[6] < threshold) cubeIndex |= 64;
        if (vals[7] < threshold) cubeIndex |= 128;

        const edges = edgeTable[cubeIndex];
        if (edges === 0) continue; // Cube is entirely in/out of the surface

        // Geographic coordinates of corners
        coords[0] = { lon: lon[x],   lat: lat[y],   depth: depth[z] };
        coords[1] = { lon: lon[x+1], lat: lat[y],   depth: depth[z] };
        coords[2] = { lon: lon[x+1], lat: lat[y+1], depth: depth[z] };
        coords[3] = { lon: lon[x],   lat: lat[y+1], depth: depth[z] };
        coords[4] = { lon: lon[x],   lat: lat[y],   depth: depth[z+1] };
        coords[5] = { lon: lon[x+1], lat: lat[y],   depth: depth[z+1] };
        coords[6] = { lon: lon[x+1], lat: lat[y+1], depth: depth[z+1] };
        coords[7] = { lon: lon[x],   lat: lat[y+1], depth: depth[z+1] };

        // Find intersected edges and interpolate
        if (edges & 1) edgeVerts[0] = interpolateGeographic(threshold, vals[0], vals[1], coords[0], coords[1]);
        if (edges & 2) edgeVerts[1] = interpolateGeographic(threshold, vals[1], vals[2], coords[1], coords[2]);
        if (edges & 4) edgeVerts[2] = interpolateGeographic(threshold, vals[2], vals[3], coords[2], coords[3]);
        if (edges & 8) edgeVerts[3] = interpolateGeographic(threshold, vals[3], vals[0], coords[3], coords[0]);
        if (edges & 16) edgeVerts[4] = interpolateGeographic(threshold, vals[4], vals[5], coords[4], coords[5]);
        if (edges & 32) edgeVerts[5] = interpolateGeographic(threshold, vals[5], vals[6], coords[5], coords[6]);
        if (edges & 64) edgeVerts[6] = interpolateGeographic(threshold, vals[6], vals[7], coords[6], coords[7]);
        if (edges & 128) edgeVerts[7] = interpolateGeographic(threshold, vals[7], vals[4], coords[7], coords[4]);
        if (edges & 256) edgeVerts[8] = interpolateGeographic(threshold, vals[0], vals[4], coords[0], coords[4]);
        if (edges & 512) edgeVerts[9] = interpolateGeographic(threshold, vals[1], vals[5], coords[1], coords[5]);
        if (edges & 1024) edgeVerts[10] = interpolateGeographic(threshold, vals[2], vals[6], coords[2], coords[6]);
        if (edges & 2048) edgeVerts[11] = interpolateGeographic(threshold, vals[3], vals[7], coords[3], coords[7]);

        // Form triangles
        for (let i = 0; triTable[cubeIndex * 16 + i] !== -1; i += 3) {
          const v0Geo = edgeVerts[triTable[cubeIndex * 16 + i]];
          const v1Geo = edgeVerts[triTable[cubeIndex * 16 + i + 1]];
          const v2Geo = edgeVerts[triTable[cubeIndex * 16 + i + 2]];

          // Convert Geographic -> Spherical exactly as requested
          const v0Sph = toSpherical(v0Geo, verticalExaggeration);
          const v1Sph = toSpherical(v1Geo, verticalExaggeration);
          const v2Sph = toSpherical(v2Geo, verticalExaggeration);

          positions.push(
            v0Sph.x, v0Sph.y, v0Sph.z,
            v1Sph.x, v1Sph.y, v1Sph.z,
            v2Sph.x, v2Sph.y, v2Sph.z
          );
        }
      }
    }
  }

  return {
    positions: new Float32Array(positions)
  };
}
